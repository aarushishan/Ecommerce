from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from app.schemas.product import ProductSummaryOut


class ChatRequest(BaseModel):
    query: str = Field(..., min_length=1, max_length=1000, description="User input message or question")
    session_id: Optional[str] = Field(None, description="Optional conversational session identifier")
    context: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Optional client context like current product or page")


class ChatResponse(BaseModel):
    message: str = Field(..., description="Conversational text response generated by SphereBot")
    intent: str = Field(..., description="Detected user intent category")
    suggested_products: List[ProductSummaryOut] = Field(default_factory=list, description="Grounded product matches directly from active catalog")
    quick_replies: List[str] = Field(default_factory=list, description="Contextual quick reply suggestions")
    order_info: Optional[Dict[str, Any]] = Field(None, description="Itemized status info if intent is order tracking")


class SemanticSearchOut(BaseModel):
    query: str
    parsed_intent: Dict[str, Any]
    products: List[ProductSummaryOut]
    total: int


class ProductComparisonRequest(BaseModel):
    product_ids: List[str] = Field(..., min_length=2, max_length=4, description="List of 2 to 4 product IDs to compare")


class ProductComparisonItem(BaseModel):
    product: ProductSummaryOut
    specs: Dict[str, Any]
    highlights: List[str]
    value_score: float


class ProductComparisonOut(BaseModel):
    items: List[ProductComparisonItem]
    common_attributes: List[str]
    verdict: str


class RecommendationFeedOut(BaseModel):
    title: str
    strategy: str
    products: List[ProductSummaryOut]
